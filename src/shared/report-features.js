(function (root) {
  const ALLOWED = {
    "image/png": "png",
    "image/jpeg": "jpg",
    "image/webp": "webp",
    "video/mp4": "mp4",
    "video/webm": "webm",
  };
  async function validateEvidence(file) {
    if (!file || !ALLOWED[file.type])
      throw new Error("Choose a PNG, JPEG, WebP, MP4, or WebM file.");
    if (!file.size || file.size > 25 * 1024 * 1024)
      throw new Error("Evidence files must be between 1 byte and 25 MB.");
    const bytes = new Uint8Array(await file.slice(0, 16).arrayBuffer());
    const ascii = (start, end) =>
      String.fromCharCode(...bytes.slice(start, end));
    const valid =
      file.type === "image/png"
        ? bytes[0] === 137 && ascii(1, 4) === "PNG"
        : file.type === "image/jpeg"
          ? bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255
          : file.type === "image/webp"
            ? ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP"
            : file.type === "video/mp4"
              ? ascii(4, 8) === "ftyp"
              : bytes[0] === 26 &&
                bytes[1] === 69 &&
                bytes[2] === 223 &&
                bytes[3] === 163;
    if (!valid)
      throw new Error("File content does not match its selected media type.");
    return { type: file.type, extension: ALLOWED[file.type] };
  }
  function markdownSummary(report, name, groups = []) {
    const clean = (value) =>
      String(value ?? "Unavailable")
        .replace(/[\r\n]/g, " ")
        .replace(/[\\`*_{}\[\]<>|]/g, (char) => "\\" + char);
    const c = report.counts;
    const m = report.metadata || {};
    return (
      `# Tomatoes run summary\n\nReport: ${clean(name)}\n\n` +
      Object.entries(m)
        .filter(([, value]) => value)
        .map(([key, value]) => `- ${key}: ${clean(value)}`)
        .join("\n") +
      `\n\nStarted: ${clean(report.start)}\n\nFinished: ${clean(report.end)}\n\n| Tests | Passed | Failed | Pending | Skipped |\n| --- | --- | --- | --- | --- |\n| ${c.total} | ${c.passed} | ${c.failed} | ${c.pending} | ${c.skipped} |\n\nRegistered-test pass rate: ${report.passRate.toFixed(1)}%.\n\n## Failure groups\n\n` +
      (groups
        .slice(0, 10)
        .map(
          (group) =>
            `- **${group.tests.length} tests / ${group.specs.length} specs:** ${clean(group.fingerprint)}`,
        )
        .join("\n") || "No failures recorded.") +
      "\n\nGenerated by Tomatoes. Message groups are investigation signals.\n"
    );
  }
  const api = { validateEvidence, markdownSummary };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.ReportFeatures = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
